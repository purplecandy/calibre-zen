"""
The desktop's colour schemes, as the CSS variables shadcn/ui reads.

The web app (`web/` at the top of the repo) is built with shadcn/ui, whose
components are coloured by about twenty variables: --background, --primary,
--muted-foreground and so on. Five of the desktop's six schemes are shadcn's
own neutral presets already (`theme/tokens/schemes.py`), so this is a
translation back, not a new palette: the same ramp steps, read off the same
`Scheme`, so the browser and the window agree on every grey.

The output is checked in at `web/src/styles/tokens.css`, because the web
build runs under Node and cannot import calibre. `test_web` fails when it is
out of date. Regenerate with:

    CALIBRE_DEVELOP_FROM=$PWD/src calibre-debug -c \\
        'from calibre_zen.web.tokens import main; main()'

Selectors. The page always carries `data-scheme`, and `dark`, `dark dim` or
neither as classes on <html>, which is what the app's first script sets
before anything paints. `:root` alone is neutral light, for the moment before
that script runs.
"""

import os

from calibre_zen.theme.tokens import schemes

OUTPUT = ('web', 'src', 'styles', 'tokens.css')


def variables(scheme: schemes.Scheme, mode: str) -> dict[str, str]:
    "shadcn's variables for `mode`, one of light, dark or dim."
    is_dark = mode != 'light'
    dim = mode == 'dim'
    r = scheme.roles(is_dark, dim=dim)
    n = scheme.named(is_dark, dim=dim)
    i = 0 if is_dark else 1  # the (dark, light) pairs
    card = n.get('surface', r['Window'] if is_dark else r['Base'])
    return {
        'background': r['Base'],
        'foreground': r['Text'],
        'card': card,
        'card-foreground': r['Text'],
        'popover': card,
        'popover-foreground': r['Text'],
        'primary': r['Highlight'],
        'primary-foreground': r['HighlightedText'],
        'secondary': r['Midlight'],
        'secondary-foreground': r['ButtonText'],
        'muted': r['Midlight'],
        'muted-foreground': n.get('muted', r['PlaceholderText']),
        'accent': n.get('surface_hover', r['Midlight']),
        'accent-foreground': r['Text'],
        'destructive': scheme.danger[i],
        'success': scheme.success[i],
        'border': n.get('border', r['Mid']),
        'input': n.get('border_strong', r['Mid']),
        'ring': r['PlaceholderText'],
        'link': r['Link'],
        'sidebar': r['Window'],
        'sidebar-foreground': r['WindowText'],
        'sidebar-primary': r['Highlight'],
        'sidebar-primary-foreground': r['HighlightedText'],
        'sidebar-accent': n.get('surface_hover', r['Midlight']),
        'sidebar-accent-foreground': r['WindowText'],
        'sidebar-border': n.get('border', r['Mid']),
        'sidebar-ring': r['PlaceholderText'],
    }


def radius(scheme: schemes.Scheme) -> str:
    """
    shadcn's base radius, from the scheme's largest step. Its scale is drawn
    for controls about 36px tall, which is what a web page has, so the base
    is taken as the scheme states it rather than at the desktop's density.
    """
    return f'{scheme.radius["xl"] / 16:g}rem'


def block(selector: str, values: dict[str, str]) -> str:
    lines = [f'{selector} {{']
    lines += [f'  --{k}: {v};' for k, v in values.items()]
    lines.append('}')
    return '\n'.join(lines)


def css() -> str:
    out = [
        "/* Generated by src/calibre_zen/web/tokens.py from the desktop's colour schemes. Do not edit. */",
        '',
    ]
    default = schemes.SCHEMES[schemes.DEFAULT]
    out.append(block(':root', {**variables(default, 'light'), 'radius': radius(default)}))
    for name, scheme in schemes.SCHEMES.items():
        sel = f":root[data-scheme='{name}']"
        out.append('')
        out.append(block(sel, {**variables(scheme, 'light'), 'radius': radius(scheme)}))
        out.append('')
        out.append(block(f'{sel}.dark', variables(scheme, 'dark')))
        if scheme.dim:
            out.append('')
            out.append(block(f'{sel}.dark.dim', variables(scheme, 'dim')))
    return '\n'.join(out) + '\n'


def output_path() -> str:
    d = os.path.dirname
    repo = d(d(d(d(os.path.abspath(__file__)))))
    return os.path.join(repo, *OUTPUT)


def main() -> None:
    path = output_path()
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css())
    print('Wrote', path)
